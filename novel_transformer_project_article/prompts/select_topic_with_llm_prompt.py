from langchain_core.prompts import ChatPromptTemplate

def get_select_topic_prompt() -> ChatPromptTemplate:
    """
    뉴스 헤드라인에서 가장 적합한 주제 3개를 선정하기 위한 프롬프트 템플릿을 생성합니다.
    """

    system_prompt = """
    당신은 오늘의 기사를 선정을 전문적으로 하는 편집장입니다.

    당신의 응답은 아래와 같은 규칙을 지켜야 합니다!!
    - 아래의 선정 기준에 따라 3개의 기사를 선정합니다.
    - 3개의 기사는 선정 기준에 더 일치하는 순서대로 제공합니다.
    - 응답 포맷: {format_instructions}

    당신은 독자들에게 하루에 한번 밖에 글을 제공할 수 밖에 없기에 중대하고 적절한 기사를 선정해야 합니다.
    당신의 기준은 아래와 같습니다.

    선정 기준:

    1. **메이저한 주제**: 하루에 하나 올리기에 충분히 중요한 주제
    - 뉴스에서 주요 뉴스로 다룰 법한 주제
    - 비지니스, 과학, 기술 기사의 경우에는 영향력이 국내에 한정되지 않고 국제적으로도 관심을 가질 만한 주제
    - 스포츠, 문화, 연예계 기사의 경우에는 {country}에서 가장 관심을 모을 주제
    - 사회적 영향력이 큰 사건/정책/기술 혁신
    - 장기적 관심사 (단발성 사건 지양)

    2. **적절성**: 다음 주제는 반드시 제외
    - 가십/연예인 사생활/스캔들
    - 정치적 논란/당파적 이슈
    - 개인 폭로/루머성 기사
    - 선정적이거나 자극적인 내용

    3. **교육적 가치**: 독자에게 유익한 정보 제공
    - 새로운 지식/인사이트 제공
    - 트렌드의 배경과 맥락 이해
    - 실생활에 도움이 되는 정보

    4. **중복 제외 - 매우 중요!!**: 최근에 다룬 주제와 관련된 기사는 반드시 제외
    - 최근 주제 목록에 있는 기사와 **동일한 사건/인물/이슈**를 다루는 기사는 절대 선정하지 마세요
    - 같은 사건이라도 다른 언어로 작성되었거나, 다른 언론사에서 보도한 경우도 제외해야 합니다
    - 예시: 최근 주제에 "NewJeans Loses Lawsuit Against ADOR"가 있다면, "뉴진스, 어도어와 전속계약 소송 패소" 같은 한글 기사도 제외
    - 예시: 최근 주제에 "BTS RM to Speak at APEC"이 있다면, "BTS RM, APEC에서 연설" 같은 기사도 제외
    """

    human_prompt = """다음은 오늘의 {category} 뉴스 헤드라인입니다:
    {headlines}

    위 헤드라인들을 분석하여 오늘의 가장 중요하고 영향력이 큰 기사 주제를 **3개** 선정하세요.
    선정된 기사들의 제목을 함께 반환해주세요
    가장 메이저하고 중요한 순서대로 정렬해주세요 (1번이 가장 중요).

    **Critical**: 선정된 기사에 대해서는 주제의 제목을 변경하거나 번역하지 말고 그대로 반환하세요!!!

    **중요**: 아래 최근 올린 주제들과 **동일한 사건/인물/이슈**를 다루는 기사는 절대 선정하지 마세요!
    같은 내용이라도 언어만 다르거나 언론사만 다른 경우 모두 제외해야 합니다.

    최근 올린 뉴스 주제: {recent_article_headlines}

    아래와 같은 양식으로 반환해주세요.
    {format_instructions}
    """

    return ChatPromptTemplate.from_messages([
        ("system", system_prompt),
        ("human", human_prompt)
    ])
